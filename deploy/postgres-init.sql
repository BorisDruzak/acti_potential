\set ON_ERROR_STOP on
\getenv app_password ACTI_APP_PASSWORD
\getenv owner_password ACTI_OWNER_PASSWORD
CREATE ROLE acti_owner LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'owner_password';
CREATE ROLE acti_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'app_password';
ALTER DATABASE acti OWNER TO acti_owner;
REVOKE ALL ON DATABASE acti FROM PUBLIC;
GRANT CONNECT ON DATABASE acti TO acti_owner, acti_app;
ALTER SCHEMA public OWNER TO acti_owner;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
